/** 입력칸이 받아 줄 글자만 남긴다 (2026-11-08).
 *
 * 걸러 내는 자리는 **화면이 아니라 여기**다 — 붙여넣기·끌어다 놓기·IME 확정·자동 완성이
 * 저마다 다른 경로로 들어오므로, 키 입력만 막으면 셋이 그대로 통과한다.
 * 화면은 `input` 한 곳에서 이 함수를 거친 값만 쓴다.
 *
 * 쓰는 쪽에서 되쓰기(`el.value = …`)는 **걸러 낸 것이 있을 때만** 한다.
 * 조합 중에 값을 되쓰면 한글이 깨진다.
 */

/** 나이 칸 — 숫자만. `type="number"`가 받아 주던 `-`·`.`·`e`도 지운다 */
export function digitsOnly(v: string): string {
  return v.replace(/[^0-9]/g, '')
}

/* 한글(완성자·낱자)·영문·숫자·공백. 낱자(ㄱ-ㅎ, ㅏ-ㅣ)를 빼면 조합 중인 글자가 지워져
   한글을 칠 수 없다 */
const PLAIN = /[^가-힣ㄱ-ㅎㅏ-ㅣa-zA-Z0-9 ]/g

/** 사람·기관 이름 칸(이름·대학·학과) — 특수문자를 지운다 */
export function plainName(v: string): string {
  return v.replace(PLAIN, '')
}
